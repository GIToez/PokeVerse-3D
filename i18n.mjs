const MAP_IDS = { kanto: 'Kanto', pallet_route1: 'Pallet Town & Route 1', pallet_rota1: 'Pallet Town & Route 1', '1000001': 'Kanto' };
const TOWNS = new Set(['Pallet', 'Lavender']);
