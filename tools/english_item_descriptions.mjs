function tidy(s) {
  return String(s || '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:!?])/g, '$1')
    .replace(/,\s*,/g, ',')
    .replace(/\.\s*\./g, '.')
    .replace(/\bde de\b/gi, 'of')
    .replace(/\bda da\b/gi, 'of')
    .replace(/\bin the shop de\b/gi, 'in the')
    .replace(/\bto the aumento\b/gi, 'to raise')
    .replace(/\bcan be used to o\b/gi, 'used to')
    .trim();
}

function translate(s, id, it) {
  if (!s) return s;
  if (BY_ID[id]) return BY_ID[id];
  if (it?.t === 8 && /fragmentos podem formar/i.test(s)) {
    return s.replace(/(\d+)\s*fragmentos podem formar 1\s+/gi, '$1 shards can form 1 ');
  }
  if (it?.t === 4) {
    const name = String(it.n || '').replace(/\s*\[TM\]$/i, '');
    const acc = s.match(/Accuracy:\s*(\d+)/i);
    const pow = s.match(/Power:\s*(\d+)/i);
    return tidy(`Teaches the move ${name}.` + (acc ? ` Accuracy: ${acc[1]}.` : '') + (pow ? ` Power: ${pow[1]}.` : ''));
  }
  let out = s;
  for (const [a, b] of PHRASE) out = out.split(a).join(b);
  for (const [re, b] of HELD) out = out.replace(re, b);
  for (const [re, b] of WORD) out = out.replace(re, b);
  return tidy(out);
}

const leftover = /[áàâãéêíóôõúçÁÀÂÃÉÊÍÓÔÕÚÇ]|\b(você|mochila|personagem|usado para|Pode |Este medicamento|Escolha um|aliado|carrega este item)\b/;
let n = 0, still = 0;
for (const [id, it] of Object.entries(dados.itens || {})) {
  if (!it?.d) continue;
  const next = translate(it.d, +id, it);
  if (next !== it.d) {
    if (!uiEn[it.d]) uiEn[it.d] = next;
    if (!uiPt[next]) uiPt[next] = it.d;
    it.d = next;
    n++;
  }
  if (leftover.test(it.d.replace(/Pokémon|Poké Ball|Pokédex/g, ''))) still++;
}

fs.writeFileSync(dataPath, JSON.stringify(dados));
fs.writeFileSync(uiEnPath, JSON.stringify(uiEn, null, 2) + '\n');
fs.writeFileSync(uiPtPath, JSON.stringify(uiPt, null, 2) + '\n');
console.log(JSON.stringify({ renamed: n, stillLooksPt: still }));
