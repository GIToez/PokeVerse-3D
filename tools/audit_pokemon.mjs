/* Generates docs/audit/POKEMON.md from the game data: every Pokémon with a 3D model, and every wild spawn table by area.
 * Usage: node tools/audit_pokemon.mjs   (re-run after adding models or editing habitats)
 *
 * Sources: public/scenery/mon/*.glb (models), public/pokedex.json (names/types), public/data/habitats.json (spawns),
 * public/data/config_jogo.json → nivelArea (levels), public/data/cenas.json (area names, translated with locale/*_en.json). */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const RAIZ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ler = p => JSON.parse(fs.readFileSync(path.join(RAIZ, p), 'utf8'));

const dex = new Map(ler('public/pokedex.json').species.map(s => [s.n, s]));
const extra = ler('public/data/dex_extra.json').especies || {};
const nomeDe = n => dex.get(n)?.name || extra[n]?.nome || extra[n]?.name || '#' + n;
const tiposDe = n => (dex.get(n)?.types || []).join('/');

const dic = {};
for (const n of ['nomes', 'conteudo', 'ui']) Object.assign(dic, ler('public/data/locale/' + n + '_en.json'));
const padroes = Object.entries(dic).filter(([k]) => /\{\w+\}/.test(k) && !/^\{\w+\}$/.test(k)).map(([k, v]) => {
  const partes = k.split(/(\{\w+\})/); let re = '^'; const vars = [];
  for (const p of partes) { const m = /^\{(\w+)\}$/.exec(p); if (m) { vars.push(m[1]); re += '(.+?)'; } else re += p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
  return { re: new RegExp(re + '$'), v, vars, tam: k.length };
}).sort((a, b) => b.tam - a.tam);
function ingles(s) {
  if (!s) return s;
  if (typeof dic[s] === 'string') return dic[s];
  for (const p of padroes) { const m = p.re.exec(s); if (m) return p.v.replace(/\{(\w+)\}/g, (t, n) => { const i = p.vars.indexOf(n); return i >= 0 ? ingles(m[i + 1]) : t; }); }
  return s;
}

const areaNome = {};
for (const c of ler('public/data/cenas.json').cenas || []) for (const a of c.areas || []) areaNome[a.id] = ingles(a.nome);

const PASTA = path.join(RAIZ, 'public/scenery/mon');
const porEspecie = new Map();
for (const f of fs.readdirSync(PASTA).filter(f => /^pm\d{4}.*\.glb$/.test(f)).sort()) {
  const n = +f.slice(2, 6);
  if (!porEspecie.has(n)) porEspecie.set(n, []);
  porEspecie.get(n).push(f);
}
const geracao = n => n <= 151 ? 1 : n <= 251 ? 2 : n <= 386 ? 3 : n <= 493 ? 4 : n <= 649 ? 5 : n <= 721 ? 6 : n <= 809 ? 7 : n <= 905 ? 8 : 9;

const hab = ler('public/data/habitats.json');
const niveis = ler('public/data/config_jogo.json').nivelArea || {};
const spawnam = new Set();
for (const lista of Object.values(hab.areas || {})) for (const s of lista) spawnam.add(s.dex);

const L = [];
L.push('# Pokémon content audit', '');
L.push('Generated by `node tools/audit_pokemon.mjs` from the game data. Do not edit by hand; re-run the tool instead.', '');
const porGen = {};
for (const n of porEspecie.keys()) porGen[geracao(n)] = (porGen[geracao(n)] || 0) + 1;
const arquivos = [...porEspecie.values()].reduce((a, b) => a + b.length, 0);
L.push('## Summary', '');
L.push('| Metric | Count |', '|---|---:|');
L.push('| Species with a 3D model | ' + porEspecie.size + ' |');
L.push('| Model files (`public/scenery/mon/*.glb`) | ' + arquivos + ' |');
for (const g of Object.keys(porGen).sort((a, b) => a - b)) L.push('| Gen ' + g + ' species with a model | ' + porGen[g] + ' |');
L.push('| Species in the Pokédex data | ' + dex.size + ' |');
L.push('| Species that spawn in the wild | ' + spawnam.size + ' |');
L.push('| Areas with wild spawns | ' + Object.keys(hab.areas || {}).length + ' |', '');
L.push('Model file names are `pm<dex>_<form>.glb`. `_00` (or no suffix) is the default form; `_51`, `_52`, `_81` and `_90`–`_94` are alternate forms (Megas, costumes, riders). Shiny is not a separate model: the game swaps the texture at runtime.', '');

L.push('## Every Pokémon with a 3D model', '');
L.push('| Dex | Name | Type | Gen | Spawns in wild | Model files |', '|---:|---|---|---:|:---:|---|');
for (const [n, fs_] of [...porEspecie].sort((a, b) => a[0] - b[0]))
  L.push('| ' + n + ' | ' + nomeDe(n) + ' | ' + tiposDe(n) + ' | ' + geracao(n) + ' | ' + (spawnam.has(n) ? 'yes' : '') + ' | ' + fs_.map(f => '`' + f + '`').join(', ') + ' |');
L.push('');

L.push('## Wild spawns by area', '');
L.push('Levels come from `config_jogo.json` → `nivelArea`. Weight is the relative spawn chance (default 100; higher is more common). "water" means the Pokémon only appears on water.', '');
const ids = Object.keys(hab.areas || {}).sort((a, b) => a - b);
for (const id of ids) {
  const lv = niveis[id];
  L.push('### ' + (areaNome[id] || 'Area ' + id) + ' (area ' + id + ')' + (lv ? ' · Lv ' + lv[0] + '–' + lv[1] : ''), '');
  L.push('| Dex | Name | Weight | Water |', '|---:|---|---:|:---:|');
  for (const s of [...hab.areas[id]].sort((a, b) => (b.peso ?? 100) - (a.peso ?? 100) || a.dex - b.dex))
    L.push('| ' + s.dex + ' | ' + nomeDe(s.dex) + ' | ' + (s.peso ?? 100) + ' | ' + (s.agua ? 'water' : '') + ' |');
  L.push('');
}
if (hab.generico) L.push('Fallback for areas without a table: ' + hab.generico.map(s => nomeDe(s.dex)).join(', ') + '.', '');

const sem = [...dex.keys()].filter(n => !porEspecie.has(n)).sort((a, b) => a - b);
L.push('## Pokédex species without a 3D model (' + sem.length + ')', '');
L.push('These exist in the Pokédex data (stats, types, learnsets) but cannot appear in the world until a model is added to `public/scenery/mon/`.', '');
L.push(sem.map(n => n + ' ' + nomeDe(n)).join(' · '), '');

fs.mkdirSync(path.join(RAIZ, 'docs/audit'), { recursive: true });
fs.writeFileSync(path.join(RAIZ, 'docs/audit/POKEMON.md'), L.join('\n'));
console.log('docs/audit/POKEMON.md', porEspecie.size, 'species with models,', spawnam.size, 'spawning,', ids.length, 'areas');
