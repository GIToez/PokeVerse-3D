/* Rebuilds the species table of public/data/ovo.json (the Day Care's breeding data) from PokéAPI's CSV files, for every species
 * the game has (dex 1–1025). Keeps every other key of ovo.json as it is.
 *
 *   git clone --depth 1 --filter=blob:none --sparse https://github.com/PokeAPI/pokeapi && git -C pokeapi sparse-checkout set data/v2/csv
 *   node tools/ovo_gen.mjs path/to/pokeapi/data/v2/csv
 *
 * Per species: nome (the game's name, dex_extra.json), macho (% male, −1 = genderless), grupos (egg group ids, same numbering as
 * ovo.json `grupos`), ciclos (hatch counter), linha (pre-evolutions → itself), base (the family's first stage), baseNoJogo (what an
 * Egg of this family hatches into: the first stage, except the incense babies — Azurill, Wynaut, Budew… — which need an incense the
 * game doesn't have, so their Eggs hatch into the next stage), cria (not in the "no eggs" group), golpesOvo (egg moves, PokéAPI
 * identifiers without hyphens, from every game that lists them for the species) and vgOvo (those games). */
import fs from 'node:fs';
import nodePath from 'node:path';

const dir = process.argv[2];
if (!dir || !fs.existsSync(nodePath.join(dir, 'pokemon_species.csv'))) { console.error('usage: node tools/ovo_gen.mjs <pokeapi data/v2/csv dir>'); process.exit(1); }
const root = nodePath.resolve(nodePath.dirname(new URL(import.meta.url).pathname), '..');
const csv = f => {
  const [h, ...rows] = fs.readFileSync(nodePath.join(dir, f), 'utf8').trim().split(/\r?\n/);
  const k = h.split(',');
  return rows.map(r => { const v = r.split(','); return Object.fromEntries(k.map((x, i) => [x, v[i]])); });
};
const MAX = 1025;
const INCENSO = new Set([298, 360, 406, 433, 438, 439, 440, 446, 458]);
const species = new Map(csv('pokemon_species.csv').map(s => [+s.id, s]));
const grupos = new Map();
for (const g of csv('pokemon_egg_groups.csv')) { const id = +g.species_id; if (!grupos.has(id)) grupos.set(id, []); grupos.get(id).push(+g.egg_group_id); }
const moveName = new Map(csv('moves.csv').map(m => [+m.id, m.identifier.replace(/-/g, '')]));
const vgs = new Map(csv('version_groups.csv').map(v => [+v.id, { id: v.identifier, ordem: +v.order }]));
// egg moves (method 2) by pokemon id (the default form's id equals the species id) and version group
const ovoPor = new Map();
for (const m of csv('pokemon_moves.csv')) {
  if (m.pokemon_move_method_id !== '2') continue;
  const p = +m.pokemon_id; if (p > MAX) continue;
  if (!ovoPor.has(p)) ovoPor.set(p, new Map());
  const vg = +m.version_group_id, M = ovoPor.get(p);
  if (!M.has(vg)) M.set(vg, new Set());
  M.get(vg).add(moveName.get(+m.move_id));
}
const ingles = new Map(csv('pokemon_species_names.csv').filter(n => n.local_language_id === '9').map(n => [+n.pokemon_species_id, n.name]));
const nomeDe = d => ingles.get(d) || species.get(d)?.identifier || '#' + d;
const linhaDe = d => { const l = [d]; let s = species.get(d); while (s?.evolves_from_species_id) { const p = +s.evolves_from_species_id; l.unshift(p); s = species.get(p); } return l; };

const arq = nodePath.join(root, 'public/data/ovo.json');
const ovo = JSON.parse(fs.readFileSync(arq, 'utf8'));
const out = {};
for (let d = 1; d <= MAX; d++) {
  const s = species.get(d); if (!s) continue;
  const linha = linhaDe(d), base = linha[0];
  const baseNoJogo = INCENSO.has(base) && linha.length > 1 ? linha[1] : base;
  const g = (grupos.get(d) || [15]).sort((a, b) => a - b);
  const M = ovoPor.get(d);
  let golpesOvo = [], vgOvo = null;
  if (M?.size) { golpesOvo = [...new Set([...M.values()].flatMap(x => [...x]))].filter(Boolean).sort(); vgOvo = [...M.keys()].sort((a, b) => (vgs.get(a)?.ordem || 0) - (vgs.get(b)?.ordem || 0)).map(v => vgs.get(v)?.id).filter(Boolean).join(' '); }
  const r = +s.gender_rate;
  out[d] = { nome: nomeDe(d), macho: r < 0 ? -1 : (8 - r) / 8 * 100, grupos: g, ciclos: +s.hatch_counter || 20, linha, base, baseNoJogo, cria: !g.includes(15),
    ...(g.includes(15) ? { naoCria: +s.is_legendary || +s.is_mythical ? 'lendario' : 'semOvo' } : {}), golpesOvo, vgOvo };
}
ovo.especies = out;
ovo.versao = 2;
ovo.nota = 'Breeding data (server_breeding.mjs). Species table generated by tools/ovo_gen.mjs from PokéAPI (dex 1–' + MAX + ') — do not edit it by hand.';
ovo.fontes = [{ arquivo: 'PokeAPI/pokeapi data/v2/csv', origem: 'pokemon_species, pokemon_egg_groups, pokemon_moves (method 2), moves, version_groups — cloned ' + new Date().toISOString().slice(0, 10) }, { arquivo: 'PokeAPI pokemon_species_names', origem: 'English names' }];
fs.writeFileSync(arq, JSON.stringify(ovo, null, 1));
const n = Object.keys(out).length, comOvo = Object.values(out).filter(e => e.golpesOvo.length).length;
console.log('ovo.json:', n, 'species,', comOvo, 'with egg moves');
